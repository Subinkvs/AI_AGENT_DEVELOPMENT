# --------------------------------------------------
# Session reset
# --------------------------------------------------

@app.delete("/sessions/{session_id}")
def clear_session(session_id: str):
    """
    Clear a conversation session.

    InMemorySaver does not expose a simple high-level delete API,
    so this endpoint provides a documented place for session reset.
    """
    return {
        "status": "ok",
        "message": (
            f"Session '{session_id}' can be started with a new "
            "session_id."
        ),
    }


# --------------------------------------------------
# Ask endpoint
# --------------------------------------------------

@app.post("/ask", response_model=AskAPIResponse)
def ask(payload: AskRequest):

    if not payload.query.strip():
        raise HTTPException(
            status_code=400,
            detail="Query cannot be empty.",
        )

    try:
        result = agent.invoke(
            {
                "messages": [
                    {
                        "role": "user",
                        "content": payload.query,
                    }
                ]
            },
            {
                "configurable": {
                    "thread_id": payload.session_id,
                }
            },
        )

        messages = result.get("messages", [])

        if not messages:
            raise HTTPException(
                status_code=500,
                detail="Agent returned no messages.",
            )

        answer = extract_final_answer(messages)
        tools_used = extract_tools_used(messages)
        sources = extract_sources(messages)

        response = ResearchResponse(
            topic=generate_topic(payload.query),
            summary=answer,
            sources=sources,
            tools_used=tools_used,
        )

        return AskAPIResponse(
            answer=response.summary,
            source=response.sources,
            tools_used=response.tools_used,
        )

    except HTTPException:
        raise

    except Exception as exc:
        raise HTTPException(
            status_code=500,
            detail=f"Agent execution failed: {exc}",
        ) from exc